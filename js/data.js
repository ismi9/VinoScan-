// Treatment recommendations mapped by disease id
function getTreatment(id) {
  const d = DISEASES.find(x => x.id === id);
  return d ? d.treatment : 'Рекомендується проконсультуватися з агрономом.';
}

function getDiseaseById(id) {
  return DISEASES.find(x => x.id === id);
}

function searchDiseases(query) {
  const q = query.toLowerCase();
  return DISEASES.filter(d => d.name.toLowerCase().includes(q) || d.symptoms.toLowerCase().includes(q));
}